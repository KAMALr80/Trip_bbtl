/** SVG path for the land outline in board units. */
export const landPath = LAND.map(
  (ring) =>
    ring
      .map(([lng, lat], i) => {
        const p = project(lat, lng);
        return `${i ? "L" : "M"}${p.x.toFixed(1)} ${p.y.toFixed(1)}`;
      })
      .join("") + "Z",
).join("");
