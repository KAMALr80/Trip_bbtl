/** A stamp's country (a name like "Portugal", a code like "PT" or a common alias) as an ISO code. */
export function countryCode(place: string | null | undefined): string | null {
  const value = (place ?? "").trim();
  if (!value) return null;
  const upper = value.toUpperCase();
  if (/^[A-Z]{2}$/.test(upper) && CENTRES[upper]) return upper;
  const lower = value.toLowerCase();
  if (ALIASES[lower]) return ALIASES[lower];
  return COUNTRIES.find((c) => c.name.toLowerCase() === lower)?.code ?? null;
}

const stateName = (state: string | null | undefined) => {
  const lower = (state ?? "").trim().toLowerCase();
  return (
    US_STATES.find((s) => s.toLowerCase() === lower) ??
    (lower === "dc" ? "District of Columbia" : null)
  );
};

export type PinPlace = { key: string; label: string; lat: number; lng: number };

/** Where a trip's pin goes: at-home rooms pin to the culture's country (R-721); US states show
 * as their own pins once zoomed in. Null when the place is unknown. */
export function pinPlace(
  trip: { country: string; state: string | null; culture: string | null; kind: string | null },
  zoomed: boolean,
  names: (code: string) => string,
): PinPlace | null {
  const code = countryCode(
    trip.kind === "postcard" ? (trip.culture ?? trip.country) : trip.country,
  );
  if (!code) return null;
  const state = code === "US" && zoomed ? stateName(trip.state) : null;
  const centre = state ? STATE_CENTRES[state] : CENTRES[code];
  if (!centre) return null;
  return {
    key: state ? `US-${state}` : code,
    label: state ?? names(code),
    lat: centre[0],
    lng: centre[1],
  };
}

/** Equirectangular projection onto a 360 × 180 board (x right, y down). */
export const project = (lat: number, lng: number) => ({ x: lng + 180, y: 90 - lat });

export type Cluster<T> = { x: number; y: number; items: T[]; places: string[] };

/** Pins closer than `cell` board units merge into one numbered bubble (R-721). */
export function clusterPins<T>(pins: { place: PinPlace; item: T }[], cell: number): Cluster<T>[] {
  const out: (Cluster<T> & { sx: number; sy: number })[] = [];
  for (const { place, item } of pins) {
    const p = project(place.lat, place.lng);
    const near = out.find((c) => Math.hypot(c.x - p.x, c.y - p.y) < cell);
    if (near) {
      near.items.push(item);
      if (!near.places.includes(place.label)) near.places.push(place.label);
      near.sx += p.x;
      near.sy += p.y;
      near.x = near.sx / near.items.length;
      near.y = near.sy / near.items.length;
    } else out.push({ x: p.x, y: p.y, sx: p.x, sy: p.y, items: [item], places: [place.label] });
  }
  return out.map(({ x, y, items, places }) => ({ x, y, items, places }));
}

