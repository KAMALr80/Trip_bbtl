#!/usr/bin/env bash
# M1-09: write supabase/migrations/00000000000000_baseline.sql from a replay of the archived
# migration history (supabase/migrations_archive/). Run it again only to rebuild the baseline from
# that history; new schema changes go in new migrations after it.
#
#   MIGRATIONS_DIR=supabase/migrations_archive REPLAY_HOOK='scripts/db/make-baseline.sh' \
#     scripts/db/replay-migrations.sh "$(mktemp -d)"
#
# Runs as a replay hook (PG* point at the replayed database). The file holds:
#   1. extensions the migrations created (pg_cron, pg_net, unaccent)
#   2. the public / trip_private / legacy_archive schema (pg_dump, privileges included)
#   3. every object's privileges again, revoked and re-granted exactly: a hosted project grants new
#      objects in public to anon / authenticated by default, and pg_dump never revokes those, which
#      would re-open the functions M1-08 revoked
#   4. the rows the migrations seeded (catalog, cards, prompts, prices, settings) as INSERTs
#   5. what the migrations attached to Supabase-owned schemas: auth triggers, storage policies,
#      storage buckets (never in the migrations; created by hand on the old project), realtime
#      publication tables and pg_cron jobs
# Secrets are made fresh per database (the cron key), never copied.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="${BASELINE_OUT:-$ROOT/supabase/migrations/00000000000000_baseline.sql}"
SCHEMAS=(--schema=public --schema=trip_private --schema=legacy_archive)
PSQL=(psql -v ON_ERROR_STOP=1 -q -X -At)
strip() { sed -E '/^\\(un)?restrict /d; /^-- Dumped (from|by) /d'; }

# Rows seeded with now() carry the replay's clock; pin them to the last archived migration's date
# so the file only changes when the history does. Throwaway database, triggers off.
"${PSQL[@]}" <<'SQL'
SET session_replication_role = replica;
DO $$
DECLARE col record;
BEGIN
  FOR col IN
    SELECT c.table_schema, c.table_name, c.column_name FROM information_schema.columns c
    JOIN information_schema.tables t USING (table_schema, table_name)
    WHERE c.table_schema IN ('public', 'trip_private', 'legacy_archive') AND t.table_type = 'BASE TABLE'
      AND c.data_type IN ('timestamp with time zone', 'timestamp without time zone', 'date')
      AND c.is_generated = 'NEVER'
  LOOP
    EXECUTE format('UPDATE %I.%I SET %I = %L WHERE %I >= now() - interval ''1 day''',
                   col.table_schema, col.table_name, col.column_name,
                   '2026-10-22 00:00:00+00', col.column_name);
  END LOOP;
END $$;
SQL

{
  cat <<'SQL'
-- Baseline schema (M1-09), generated by scripts/db/make-baseline.sh from a replay of the 304
-- migrations in supabase/migrations_archive/ (Oct 1–22, 2026). Do not edit: add new migrations.

CREATE EXTENSION IF NOT EXISTS pg_cron;
CREATE EXTENSION IF NOT EXISTS pg_net WITH SCHEMA extensions;
CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA extensions;

-- ---------------------------------------------------------------------------------------------
-- Schema
SQL
  # The schemas may already exist (public always does); its comment belongs to the platform.
  pg_dump --schema-only --no-owner "${SCHEMAS[@]}" | strip |
    sed -E 's/^CREATE SCHEMA ([a-z_]+);/CREATE SCHEMA IF NOT EXISTS \1;/; /^COMMENT ON SCHEMA public /d'

  printf '\n-- ---------------------------------------------------------------------------------------------\n'
  printf -- '-- Privileges, exactly as the migrations left them (see the header).\n'
  "${PSQL[@]}" <<'SQL'
SET search_path = '';
WITH objs AS (
  SELECT 'TABLE' AS kind, c.oid::regclass::text AS name, c.relacl AS acl
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname IN ('public', 'trip_private', 'legacy_archive') AND c.relkind IN ('r', 'v', 'm', 'p', 'f')
  UNION ALL
  SELECT 'SEQUENCE', c.oid::regclass::text, c.relacl
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname IN ('public', 'trip_private', 'legacy_archive') AND c.relkind = 'S'
  UNION ALL
  SELECT CASE p.prokind WHEN 'p' THEN 'PROCEDURE' ELSE 'FUNCTION' END, p.oid::regprocedure::text, p.proacl
  FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
  LEFT JOIN pg_depend d ON d.classid = 'pg_proc'::regclass AND d.objid = p.oid AND d.deptype = 'e'
  WHERE n.nspname IN ('public', 'trip_private', 'legacy_archive') AND d.objid IS NULL AND p.prokind <> 'a'
)
SELECT format('REVOKE ALL ON %s %s FROM PUBLIC, anon, authenticated, service_role;', kind, name)
  || coalesce((
    SELECT string_agg(format(E'\nGRANT %s ON %s %s TO %s;', a.privilege_type, o.kind, o.name,
                             CASE a.grantee WHEN 0 THEN 'PUBLIC' ELSE quote_ident(a.grantee::regrole::text) END),
                      '' ORDER BY a.grantee::regrole::text, a.privilege_type)
    FROM aclexplode(o.acl) a
    WHERE a.grantee = 0 OR a.grantee::regrole::text IN ('anon', 'authenticated', 'service_role')),
    CASE WHEN o.acl IS NULL AND o.kind IN ('FUNCTION', 'PROCEDURE')
         THEN format(E'\nGRANT EXECUTE ON %s %s TO PUBLIC;', o.kind, o.name) ELSE '' END)
FROM objs o
ORDER BY kind, name;
-- Revoking a table's privileges drops its column grants too; put those back.
SELECT format('GRANT %s (%I) ON TABLE %s TO %s;', a.privilege_type, att.attname, c.oid::regclass,
              CASE a.grantee WHEN 0 THEN 'PUBLIC' ELSE quote_ident(a.grantee::regrole::text) END)
FROM pg_attribute att
JOIN pg_class c ON c.oid = att.attrelid JOIN pg_namespace n ON n.oid = c.relnamespace
CROSS JOIN LATERAL aclexplode(att.attacl) a
WHERE n.nspname IN ('public', 'trip_private', 'legacy_archive') AND att.attacl IS NOT NULL
  AND NOT att.attisdropped
  AND (a.grantee = 0 OR a.grantee::regrole::text IN ('anon', 'authenticated', 'service_role'))
ORDER BY c.oid::regclass::text, att.attname, a.grantee::regrole::text, a.privilege_type;
SQL

  printf '\n-- ---------------------------------------------------------------------------------------------\n'
  printf -- '-- Seeded rows\n'
  pg_dump --data-only --no-owner --column-inserts --rows-per-insert=100 "${SCHEMAS[@]}" \
    --exclude-table-data=trip_private.cron_keys | strip
  cat <<'SQL'
-- The photo-purge cron key, new for each database (trip_private.cron_keys holds no copied secret).
INSERT INTO trip_private.cron_keys(name, key)
VALUES ('purge_photos', encode(extensions.gen_random_bytes(32), 'hex'))
ON CONFLICT (name) DO NOTHING;

-- ---------------------------------------------------------------------------------------------
-- Supabase-owned schemas: storage buckets (all private; access through the policies below and
-- signed URLs), auth triggers, storage policies, realtime tables, cron jobs.
INSERT INTO storage.buckets (id, name, public) VALUES
  ('trip-photos', 'trip-photos', false),
  ('quest-proofs', 'quest-proofs', false),
  ('player-avatars', 'player-avatars', false),
  ('culture-photos', 'culture-photos', false),
  ('inspiration-photos', 'inspiration-photos', false),
  ('window-guide', 'window-guide', false),
  ('bug-screenshots', 'bug-screenshots', false)
ON CONFLICT (id) DO NOTHING;
SQL
  "${PSQL[@]}" <<'SQL'
SET search_path = '';
SELECT pg_get_triggerdef(t.oid, true) || ';'
FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname IN ('auth', 'storage') AND NOT t.tgisinternal
ORDER BY n.nspname, c.relname, t.tgname;
SELECT format(E'CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;',
              policyname, schemaname, tablename, permissive, cmd,
              (SELECT string_agg(CASE r WHEN 'public' THEN 'public' ELSE quote_ident(r) END, ', ')
               FROM unnest(roles) r),
              coalesce(E'\n  USING (' || qual || ')', ''),
              coalesce(E'\n  WITH CHECK (' || with_check || ')', ''))
FROM pg_policies WHERE schemaname IN ('auth', 'storage')
ORDER BY schemaname, tablename, policyname;
SELECT format('ALTER PUBLICATION supabase_realtime ADD TABLE %I.%I;', schemaname, tablename)
FROM pg_publication_tables WHERE pubname = 'supabase_realtime'
ORDER BY schemaname, tablename;
SELECT format('SELECT cron.schedule(%L, %L, %L);', jobname, schedule, command)
FROM cron.job ORDER BY jobname;
SQL
} > "$OUT"

echo "Wrote $OUT ($(wc -l < "$OUT") lines)"
