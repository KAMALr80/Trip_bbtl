// Writes the pgTAP tests that run the shared fixtures in supabase/tests/fixtures/ against the SQL
// copies of the room config and phase engine (M2-01, M2-03). The Vitest suite runs the same
// fixtures against the TypeScript copies and fails if these files are out of date.
//   bun scripts/db/fixture-tests.ts
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const fixture = (name: string) =>
  JSON.parse(readFileSync(join(root, "supabase", "tests", "fixtures", name), "utf8"));
const q = (v: string | null | undefined) =>
  v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`;
const header = (what: string) =>
  `-- Generated by scripts/db/fixture-tests.ts from supabase/tests/fixtures/${what}. Do not edit.\n`;

export function roomRulesSql(): string {
  const rooms = fixture("rooms.json") as Record<string, unknown>;
  const ids = Object.keys(rooms);
  const lines = ids.map(
    (id) =>
      `SELECT is(trip_private.room_rules(${q(id)}), ${q(JSON.stringify(rooms[id]))}::jsonb, 'room_rules(${id}) matches rooms.ts');`,
  );
  return `${header("rooms.json")}-- M2-01: the server's room rules are the same table as src/features/trip/rooms.ts.
BEGIN;
\\ir ../_helpers.psql
SELECT plan(${ids.length + 1});
${lines.join("\n")}
SELECT is(trip_private.room_rules('nope'), NULL::jsonb, 'unknown rooms have no rules');
SELECT * FROM finish();
ROLLBACK;
`;
}

type Case = {
  name: string;
  at: string;
  input: Record<string, string | number | boolean | null>;
  expect: Record<string, string | number | null>;
};
const columns: Record<string, [string, string]> = {
  phase: ["phase", "text"],
  startsAt: ["phase_starts_at", "timestamptz"],
  endsAt: ["phase_ends_at", "timestamptz"],
  tz: ["tz", "text"],
  dayIndex: ["day_index", "int"],
};

export function phaseEngineSql(): string {
  const cases = fixture("phases.json").cases as Case[];
  const lines: string[] = [];
  for (const c of cases) {
    const i = c.input;
    const call = `trip_private.phase_at(${q(String(i["room"]))}, ${q(String(i["startDate"]))}::date, ${q(String(i["endDate"]))}::date, ${Number(i["preflightDays"])}, ${i["preflightSkipped"] ? "true" : "false"}, ${q(String(i["homeTz"]))}, ${q(i["tripTz"] as string | null)}, ${q(i["arrivedAt"] as string | null)}::timestamptz, ${i["setupComplete"] ? "true" : "false"}, ${q(c.at)}::timestamptz)`;
    for (const [key, want] of Object.entries(c.expect)) {
      const [col, type] = columns[key]!;
      const value = want === null ? `NULL::${type}` : `${q(String(want))}::${type}`;
      lines.push(`SELECT is((SELECT ${col} FROM ${call}), ${value}, ${q(`${c.name}: ${key}`)});`);
    }
  }
  return `${header("phases.json")}-- M2-03: the SQL phase engine passes the same cases as src/features/trip/phase.ts.
BEGIN;
\\ir ../_helpers.psql
SELECT plan(${lines.length});
${lines.join("\n")}
SELECT * FROM finish();
ROLLBACK;
`;
}

export const generated = {
  "supabase/tests/database/13_room_rules.test.sql": roomRulesSql,
  "supabase/tests/database/14_phase_engine.test.sql": phaseEngineSql,
};

if (import.meta.main) {
  for (const [path, make] of Object.entries(generated)) writeFileSync(join(root, path), make());
  console.log(`Wrote ${Object.keys(generated).join(", ")}`);
}
