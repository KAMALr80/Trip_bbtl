#!/usr/bin/env python3
"""Build the content library seed migration (M3-02) from the two content files.

  supabase/seed/content_candidates.csv  lines mined from the Lovable-era content (M1-11), for founder review
  supabase/seed/content_starter.csv     hand-written starter items for kinds the old content lacks

Usage: python3 scripts/content/build-seed.py <output.sql>
Rows upsert on (source, source_ref), so after the founder tags or edits the files, run this again into
a new timestamped migration and the library updates in place. Flight games are left out until M4
(offline play) gives them a home.
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FOCUS = {
    "Food & drink": "food", "Music & dance": "music", "Language & slang": "language",
    "Fashion & dress": "fashion", "Holidays & traditions": "holidays", "History & heroes": "history",
    "Art & crafts": "art", "Games & sports": "games", "Manners & customs": "manners",
    "Folklore & stories": "folklore", "Film & pop culture": "film",
}


def q(v):
    if v is None or v == "":
        return "NULL"
    return "'" + str(v).replace("'", "''") + "'"


def arr(items):
    items = [i.strip() for i in items if i.strip()]
    if not items:
        return "'{}'::text[]"
    return "ARRAY[" + ", ".join(q(i) for i in items) + "]::text[]"


def rows():
    for r in csv.DictReader(open(ROOT / "supabase/seed/content_candidates.csv", newline="")):
        kind = r["suggested_kind"]
        if kind == "flight_game":
            continue
        if kind == "trip_quest" and "Window Seat" in r["review_note"]:
            kind = "ws_quest"
        yield {
            "kind": kind, "rooms": r["suggested_rooms"].split(","), "modes": r["suggested_modes"].split(","),
            "focus": FOCUS.get(r["suggested_focus"]), "culture": r["culture"] or None, "vibe": None,
            "difficulty": "medium" if kind == "sealed_quest" else None,
            "min_age": int(r["min_age"] or 13), "alcohol": r["alcohol"] == "t",
            "title": r["title"] or None, "body": r["body"], "insight": r["extra"] or None,
            "choices": [], "answer": None, "items": [],
            "source": "candidate:" + r["source"], "source_ref": r["source_ref"], "reviewed": False,
            "review_note": r["review_note"] or None,
        }
    for r in csv.DictReader(open(ROOT / "supabase/seed/content_starter.csv", newline="")):
        yield {
            "kind": r["kind"], "rooms": r["rooms"].split(","), "modes": r["modes"].split(","),
            "focus": r["focus"] or None, "culture": None, "vibe": r["vibe"] or None,
            "difficulty": r["difficulty"] or None, "min_age": 13, "alcohol": False,
            "title": r["title"] or None, "body": r["body"], "insight": r["insight"] or None,
            "choices": r["choices"].split("|") if r["choices"] else [],
            "answer": int(r["answer"]) if r["answer"] else None,
            "items": r["items"].split("|") if r["items"] else [],
            "source": "starter", "source_ref": r["key"], "reviewed": True, "review_note": None,
        }


def main(out):
    cols = ["kind", "rooms", "modes", "focus", "culture", "vibe", "difficulty", "min_age", "alcohol", "title",
            "body", "insight", "choices", "answer", "items", "source", "source_ref", "reviewed", "review_note"]
    lines = [
        "-- M3-02 content library seed. Generated by scripts/content/build-seed.py from",
        "-- supabase/seed/content_candidates.csv and content_starter.csv; don't edit by hand.",
        f"INSERT INTO public.content_items ({', '.join(cols)}) VALUES",
    ]
    values = []
    for r in rows():
        vals = []
        for c in cols:
            v = r[c]
            if c in ("rooms", "modes", "choices", "items"):
                vals.append(arr(v))
            elif c in ("alcohol", "reviewed"):
                vals.append("true" if v else "false")
            elif c in ("min_age", "answer"):
                vals.append("NULL" if v is None else str(v))
            else:
                vals.append(q(v))
        values.append("  (" + ", ".join(vals) + ")")
    lines.append(",\n".join(values))
    lines.append("ON CONFLICT (source, source_ref) DO UPDATE SET")
    lines.append("  " + ", ".join(f"{c} = excluded.{c}" for c in cols if c not in ("source", "source_ref")) + ",")
    lines.append("  updated_at = now();")
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"Wrote {len(values)} items to {out}")


if __name__ == "__main__":
    main(sys.argv[1])
